shop = [['каретка', 1200], ['шатун', 1000], ['седло', 300],
        ['педаль', 100], ['седло', 1500], ['рама', 12000],
        ['обод', 2000], ['шатун', 200], ['седло', 2700]]

name = input('Название детали: ')
summ, count = 0, 0

for detail in shop:
    if detail[0] == name:
        count += 1
        summ += detail[1]

print('Кол-во деталей —', count)
print('Общая стоимость —', summ)
